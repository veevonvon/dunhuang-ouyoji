def events(bar):
    pos = 0
    for token in bar.split():
        degree, duration = token.split(":")
        duration = int(duration)
        if degree != "r":
            yield pos, int(degree), duration
        pos += duration


def pitch(score, degree):
    octave, tone = divmod(degree, len(score.scale))
    return score.tonic + score.scale[tone] + 12 * octave
